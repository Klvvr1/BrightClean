import 'package:flutter/material.dart';

enum TermsUserRole {
  customer,
  laundryAgent,
  driver,
}

class TermsAgreementLabel extends StatelessWidget {
  final TermsUserRole role;

  const TermsAgreementLabel({
    super.key,
    required this.role,
  });

  @override
  Widget build(BuildContext context) {
    final theme = Theme.of(context);
    final textStyle = theme.textTheme.bodyMedium;

    return Wrap(
      crossAxisAlignment: WrapCrossAlignment.center,
      children: [
        Text('أوافق على ', style: textStyle),
        InkWell(
          onTap: () => _showTermsDialog(context),
          child: Text(
            'الشروط والأحكام',
            style: textStyle?.copyWith(
              color: theme.colorScheme.primary,
              decoration: TextDecoration.underline,
              fontWeight: FontWeight.w600,
            ),
          ),
        ),
      ],
    );
  }

  void _showTermsDialog(BuildContext context) {
    showDialog<void>(
      context: context,
      builder: (context) {
        final theme = Theme.of(context);
        return AlertDialog(
          title: Text(_title),
          content: SizedBox(
            width: double.maxFinite,
            child: SingleChildScrollView(
              child: Text(
                _content,
                textAlign: TextAlign.right,
                style: theme.textTheme.bodyMedium?.copyWith(height: 1.6),
              ),
            ),
          ),
          actions: [
            TextButton(
              onPressed: () => Navigator.of(context).pop(),
              child: const Text('إغلاق'),
            ),
          ],
        );
      },
    );
  }

  String get _title {
    switch (role) {
      case TermsUserRole.customer:
        return 'شروط وأحكام العميل';
      case TermsUserRole.laundryAgent:
        return 'شروط وأحكام مدير المغسلة';
      case TermsUserRole.driver:
        return 'شروط وأحكام المندوب';
    }
  }

  String get _content {
    switch (role) {
      case TermsUserRole.customer:
        return '''
1. يلتزم العميل بإدخال بيانات صحيحة ومحدثة، ويشمل ذلك الاسم، رقم الهاتف، البريد الإلكتروني، وعنوان الاستلام والتسليم.

2. يتحمل العميل مسؤولية اختيار الخدمة والمغسلة والعنوان قبل تأكيد الطلب، ولا تتحمل المنصة أي مسؤولية عن خطأ ناتج عن بيانات غير صحيحة أدخلها العميل.

3. الأسعار المعروضة داخل التطبيق هي الأسعار المعتمدة وقت إنشاء الطلب، وقد تختلف حسب نوع الخدمة والكمية والعروض المتاحة.

4. لا يعد الطلب مؤكداً إلا بعد إتمام خطوات الدفع أو اختيار وسيلة دفع مقبولة داخل النظام وظهور الطلب في سجل الطلبات.

5. في حال الدفع الإلكتروني أو عبر المحفظة، يكون سجل الدفع داخل النظام هو المرجع الأساسي لإثبات السداد.

6. في حال الدفع نقداً أو التحويل البنكي، يحق للمنصة أو الإدارة مراجعة حالة الدفع واعتمادها أو رفضها وفق البيانات المتوفرة في النظام.

7. لا يحق للعميل المطالبة باسترداد أي مبلغ بعد بدء تنفيذ الخدمة أو استلام الملابس/الأغراض أو وصول الفني إلى موقع الخدمة، إلا إذا أقرت الإدارة بوجود خطأ واضح من مزود الخدمة.

8. في حال إلغاء الطلب قبل بدء التنفيذ، يحق للمنصة تحديد قبول الإلغاء أو رفضه حسب حالة الطلب ومرحلة المعالجة.

9. أي استرداد مالي، إن وجد، يتم وفق قرار الإدارة وبالطريقة التي تراها المنصة مناسبة، وقد يتم إرجاعه إلى المحفظة أو وسيلة الدفع الأصلية أو تسويته يدوياً.

10. يقر العميل بأن المنصة هي المرجع النهائي في النزاعات المالية داخل التطبيق، ويحق لها مراجعة الطلبات والمدفوعات والسجلات قبل اتخاذ أي قرار.

11. يلتزم العميل بالتعامل اللائق مع المغاسل والمندوبين، ويحق للمنصة تعليق الحساب عند إساءة الاستخدام أو تقديم بلاغات غير صحيحة.
''';
      case TermsUserRole.laundryAgent:
        return '''
1. يقر مدير المغسلة بأن التسجيل في المنصة لا يعني قبول الحساب تلقائياً، ويخضع الحساب والمستندات لمراجعة الإدارة.

2. يلتزم مدير المغسلة بتقديم بيانات ومستندات صحيحة، بما في ذلك السجل التجاري والهوية الوطنية وبيانات التواصل والحساب البنكي.

3. لا تظهر خدمات المغسلة للعملاء إلا بعد اعتماد الحساب وتفعيل الخدمات من قبل الإدارة وفق سياسات المنصة.

4. يلتزم مدير المغسلة بتقديم الخدمات التي تم اعتمادها فقط، ولا يحق له تنفيذ خدمة غير مفعلة أو غير معروضة له داخل النظام.

5. الأسعار المعتمدة داخل التطبيق هي الأسعار الملزمة للمغسلة، ولا يحق للمغسلة مطالبة العميل بمبالغ إضافية خارج النظام إلا بموافقة الإدارة.

6. يلتزم مدير المغسلة بتحديث حالة الطلب بدقة وفي الوقت المناسب، بما في ذلك قبول الطلب، بدء المعالجة، جاهزية الطلب، أو الإكمال حسب نوع الخدمة.

7. عند قبول الطلب، تلتزم المغسلة بتنفيذه وفق التفاصيل المسجلة في النظام، وتتحمل مسؤولية أي تقصير أو خطأ في التنفيذ يثبت من خلال مراجعة الإدارة.

8. يحق للمنصة مراجعة الشكاوى، تقييم جودة الخدمة، تأخير الطلبات، أو مخالفة الأسعار، واتخاذ ما تراه مناسباً بما في ذلك التحذير أو إيقاف الخدمة أو تعليق الحساب.

9. في المسائل المالية، يعد سجل النظام هو المرجع الأساسي للطلبات والمدفوعات والمستحقات، ويحق للمنصة احتجاز أو تعديل أو رفض أي تسوية مالية عند وجود نزاع أو مخالفة.

10. لا يحق للمغسلة تحصيل مبالغ مباشرة من العميل خارج آلية الدفع المعتمدة إلا إذا كان نوع الدفع داخل الطلب يسمح بذلك ووفق ما تقرره المنصة.

11. أي إلغاء أو استرداد أو تعويض مرتبط بطلب تم تنفيذه أو بدأ تنفيذه يخضع لمراجعة وقرار الإدارة، ويكون قرار المنصة هو المرجع النهائي داخل النظام.

12. يقر مدير المغسلة بأن المنصة تملك حق تعديل حالة الخدمات أو إيقافها أو طلب مستندات إضافية عند الحاجة للحفاظ على جودة وسلامة التشغيل.
''';
      case TermsUserRole.driver:
        return '''
1. يقر المندوب بأن التسجيل في المنصة لا يعني قبول الحساب تلقائياً، ويخضع الحساب والمستندات لمراجعة الإدارة.

2. يلتزم المندوب بتقديم بيانات صحيحة، بما في ذلك الهوية الوطنية، رخصة القيادة، صورة المركبة، رقم اللوحة، وبيانات التواصل.

3. لا يحق للمندوب قبول أو تنفيذ أي مهمة إلا من خلال النظام وبعد ظهورها له بشكل رسمي داخل التطبيق.

4. عند قبول المهمة، يلتزم المندوب بتنفيذ مراحل الاستلام والتسليم حسب بيانات الطلب والعناوين المسجلة داخل النظام.

5. يلتزم المندوب بتحديث حالة المهمة بدقة، مثل قبول المهمة، بدء التنفيذ، الوصول، الاستلام، التسليم، أو الإكمال حسب المرحلة المتاحة في التطبيق.

6. يتحمل المندوب مسؤولية أي تأخير أو خطأ ناتج عن عدم اتباع تعليمات الطلب أو عدم تحديث الحالة بشكل صحيح.

7. لا يحق للمندوب تحصيل مبالغ من العميل إلا إذا كانت وسيلة الدفع في الطلب تسمح بذلك، ويجب الالتزام بما يظهر داخل النظام.

8. في حال استلام مبالغ نقدية، يلتزم المندوب بتسليمها أو تسويتها وفق تعليمات الإدارة، ويعد سجل النظام مرجعاً أساسياً في تحديد المسؤولية المالية.

9. يحق للمنصة مراجعة أي نزاع متعلق بالتوصيل أو التحصيل أو تلف الأغراض أو التأخير، واتخاذ القرار المناسب وفق السجلات المتاحة.

10. أي مستحقات مالية للمندوب تخضع لمراجعة المنصة، ويحق للمنصة تأجيل أو تعديل أو رفض التسوية عند وجود مخالفة أو نزاع على المهمة.

11. يلتزم المندوب بالحفاظ على سرية بيانات العملاء والمغاسل وعدم استخدامها خارج نطاق تنفيذ المهمة.

12. يحق للمنصة تعليق حساب المندوب أو إيقافه عند مخالفة التعليمات أو تقديم بيانات غير صحيحة أو إساءة استخدام النظام.
''';
    }
  }
}
